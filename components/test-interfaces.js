'use strict';
const assert=require('node:assert/strict');
const G=require('../graph-engine.js'),D=require('../discovery.js');
const {auditRevoluteInterfaces:audit}=require('./interfaces.js');
const graph=G.fromLegacyFourbar(D.BEST_LEGACY);
const pins=Object.fromEntries(graph.joints.map(j=>[j.id,3.8]));
const groundBores=Object.fromEntries(graph.joints.filter(j=>j.a==='g'||j.b==='g').map(j=>[j.id,4]));
const opts={pins,groundBores,minRadialClearanceMm:0.05,maxRadialClearanceMm:0.15};
const ok=audit(graph,opts);
assert.equal(ok.nominalCompatible,true,JSON.stringify(ok.errors));
assert.equal(ok.rows.length,graph.joints.length);
assert(ok.rows.every(x=>x.radialClearanceMm.every(c=>Math.abs(c-0.1)<1e-8)));
assert.deepEqual(ok,audit(graph,opts),'deterministic');
const missing=audit(graph,{pins,groundBores:{}});
assert(!missing.nominalCompatible);
assert(missing.errors.some(e=>e.reason.includes('ground bore')));
const oversize=audit(graph,{...opts,pins:{...pins,A:4.5}});
assert(!oversize.nominalCompatible);
assert(oversize.errors.some(e=>e.jointId==='A'&&e.reason.includes('clearance')));
const undersize=audit(graph,{...opts,pins:{...pins,B:2}});
assert(!undersize.nominalCompatible);
assert(undersize.errors.some(e=>e.jointId==='B'));
assert(!audit(graph,{...opts,pins:{...pins,notARealJoint:3.8}}).nominalCompatible);
assert.throws(()=>audit(graph,{...opts,minRadialClearanceMm:0.3,maxRadialClearanceMm:0.1}),RangeError);
const slider=G.sliderCrank({crank:25,rod:95,offset:4,point:65,normal:25,rotation:0,phase:0});
assert.throws(()=>audit(slider,opts),/Unsupported prismatic/);
console.log('Nominal revolute interface compatibility: PASS (positive, missing, oversized, undersized, unknown, slider rejection)');
