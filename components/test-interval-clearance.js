'use strict';
const assert=require('node:assert/strict');
const G=require('../graph-engine.js'),D=require('../discovery.js');
const {auditRevoluteInterfaces}=require('./interfaces.js');
const {auditClearanceIntervals:audit}=require('./interval-clearance.js');
const graph=G.fromLegacyFourbar(D.BEST_LEGACY);
const pins=Object.fromEntries(graph.joints.map(j=>[j.id,3.8]));
const groundBores=Object.fromEntries(graph.joints.filter(j=>j.a==='g'||j.b==='g').map(j=>[j.id,4]));
const nominal=auditRevoluteInterfaces(graph,{pins,groundBores,minRadialClearanceMm:0.05,maxRadialClearanceMm:0.15});
assert(nominal.nominalCompatible);
const pinToleranceMm=Object.fromEntries(graph.joints.map(j=>[j.id,0.02]));
const boreToleranceMm=Object.fromEntries(graph.joints.map(j=>[j.id,[0.02,0.02]]));
const options={pinToleranceMm,boreToleranceMm,minRadialClearanceMm:0.05,maxRadialClearanceMm:0.15};
const ok=audit(nominal,options);
assert(ok.robustCompatible,JSON.stringify(ok.errors));
assert(ok.rows.every(r=>r.clearanceBoundsMm.every(([lo,hi])=>Math.abs(lo-0.08)<1e-9&&Math.abs(hi-0.12)<1e-9)));
assert.deepEqual(ok,audit(nominal,options));
const fail=audit(nominal,{...options,pinToleranceMm:{...pinToleranceMm,[graph.joints[0].id]:0.12}});
assert(!fail.robustCompatible&&fail.errors.some(e=>e.reason.includes('worst-case')));
assert(!audit(nominal,{...options,boreToleranceMm:{}}).robustCompatible);
assert(!audit(nominal,{...options,pinToleranceMm:{...pinToleranceMm,unknown:0}}).robustCompatible);
assert.throws(()=>audit(nominal,{...options,minRadialClearanceMm:0.3,maxRadialClearanceMm:0.1}),RangeError);
console.log('Worst-case interval clearance: PASS');
