'use strict';
const assert=require('node:assert/strict');
const {benchmark,TRAIN,HELD_OUT,objectiveShapeDistance,classifyTargets}=require('./benchmark.js');
const a=classifyTargets(),b=classifyTargets();
assert.deepEqual(a,b,'audit must be deterministic');
assert.equal(a.rows.length,4);
assert.equal(a.rows[0].role,'training-resample-control');
assert.equal(a.rows[0].duplicate_of,'TRAIN');
assert.equal(a.rows[0].shape_distance_from_training_mm,0);
assert.equal(a.independent_objectives,3);
assert.equal(a.controls,1);
assert.equal(objectiveShapeDistance(TRAIN,{...TRAIN,n:192}),0);
assert.equal(classifyTargets(TRAIN,[{...TRAIN,id:'same',n:48}]).independent_objectives,0);
assert.equal(classifyTargets(TRAIN,[{...TRAIN,id:'a',n:96},{...TRAIN,id:'b',n:144}]).controls,2);
assert.throws(()=>classifyTargets(TRAIN,HELD_OUT,{toleranceMm:-1}),RangeError);
const report=benchmark({seed:716,budget:0,depth:0});
assert.equal(report.objective_integrity.independent_objectives,3);
assert.equal(report.held_out[0].objective_role,'training-resample-control');
assert.equal(report.held_out.filter(x=>x.objective_role==='independent-objective').length,3);
console.log('benchmark independence audit PASS: 1 resampling control, 3 geometrically distinct objectives');
