'use strict';
const assert=require('node:assert/strict');
const G=require('../graph-engine.js'),D=require('../discovery.js');
const {assess,experiment}=require('./generated-interface-yield.js');
const four=G.fromLegacyFourbar(D.BEST_LEGACY);
const good=assess(four);
assert.equal(good.accepted,true,JSON.stringify(good));
assert.equal(good.kinematic,true);
assert.equal(assess(four,{pinDiameterMm:4.5}).accepted,false);
assert.equal(assess(four,{groundBoreDiameterMm:0}).accepted,false);
assert.throws(()=>assess(four,{samples:0}),RangeError);
const slider=G.sliderCrank({crank:25,rod:95,offset:4,point:65,normal:25,rotation:0,phase:0});
assert.equal(assess(slider).accepted,false,'unsupported P interface must not pass');
const a=experiment({seed:17,attempts:8,depth:1}),b=experiment({seed:17,attempts:8,depth:1});
assert.deepEqual(a,b,'seeded experiment must reproduce');
assert.equal(a.rows.length,8);
assert.equal(a.totals.attempts,8);
assert.equal(a.totals.nominalInterfaceAccepted+a.totals.rejectedOrFailed,8);
assert(a.totals.nominalInterfaceAccepted<=a.totals.kinematicallyFeasible);
assert(a.rows.every((r,i)=>r.attempt===i+1));
assert.throws(()=>experiment({attempts:0}),RangeError);
console.log('Generated candidate nominal-interface gate: PASS (positive, adversarial, unsupported, seeded counts)');
